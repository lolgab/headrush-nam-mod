#!/usr/bin/env bash
# build_deps_macos.sh -- builds static xz (liblzma), e2fsprogs (the same 5
# libraries as build_e2fsprogs_windows.sh) and SDL2 for ONE macOS arch,
# installing them into $PREFIX, plus $PREFIX/deps.cmake: a CMake initial-
# cache file (`cmake -C`) presetting every dependency variable
# CMakeLists.txt would otherwise search for.
#
# Why not Homebrew: Homebrew no longer installs on x86_64 macOS at all --
# its installer exits with "Homebrew on macOS is only supported on Apple
# Silicon processors!", including under Rosetta on an arm64 runner, which
# is how the x86_64 half of the universal release binary used to get its
# dependencies. Building from source with `clang -arch <arch>` cross-
# compiles from either host arch, so no Rosetta is needed either. Static
# libs also mean the release binary no longer needs anything installed on
# the user's Mac (it used to dynamically link Homebrew's SDL2, which Intel
# users can no longer install).
#
# libcurl is NOT built: the macOS SDK ships libcurl.tbd + headers as part
# of the OS (universal), so deps.cmake just points at those.
#
# Usage: ./scripts/build_deps_macos.sh <arm64|x86_64> [prefix]
#   Env overrides: MACOSX_DEPLOYMENT_TARGET (default 11.0).
set -euo pipefail

XZ_VERSION=5.8.1
E2FSPROGS_VERSION=1.47.1
SDL2_VERSION=2.32.10

ARCH="${1:?usage: $0 <arm64|x86_64> [prefix]}"
PREFIX="${2:-$(cd "$(dirname "$0")/.." && pwd)/build/deps-macos-$ARCH}"
export MACOSX_DEPLOYMENT_TARGET="${MACOSX_DEPLOYMENT_TARGET:-11.0}"

die() { echo "ERROR: $*" >&2; exit 1; }

case "$ARCH" in
    arm64)  HOST=aarch64-apple-darwin ;;
    x86_64) HOST=x86_64-apple-darwin ;;
    *) die "unknown arch '$ARCH' (expected arm64 or x86_64)." ;;
esac
command -v curl >/dev/null 2>&1 || die "curl not found in PATH."
command -v make >/dev/null 2>&1 || die "make not found in PATH."
command -v cmake >/dev/null 2>&1 || die "cmake not found in PATH."

SDK="$(xcrun --show-sdk-path)"
JOBS="$(sysctl -n hw.ncpu)"
export CC="clang -arch $ARCH"
export CFLAGS="-O2"

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

fetch() {  # url
    echo "Downloading $1..."
    curl -fsSL --retry 5 --retry-all-errors -o "$WORK/src.tar.gz" "$1"
    tar -xzf "$WORK/src.tar.gz" -C "$WORK" && rm "$WORK/src.tar.gz"
}

fetch "https://github.com/tukaani-project/xz/releases/download/v$XZ_VERSION/xz-$XZ_VERSION.tar.gz"
echo "Building xz for $ARCH..."
(cd "$WORK/xz-$XZ_VERSION" &&
    ./configure --host="$HOST" --prefix="$PREFIX" --disable-shared \
        --disable-xz --disable-xzdec --disable-lzmadec --disable-lzmainfo \
        --disable-scripts --disable-doc --disable-nls &&
    make -j"$JOBS" -C src/liblzma && make -C src/liblzma install)

fetch "https://mirrors.edge.kernel.org/pub/linux/kernel/people/tytso/e2fsprogs/v$E2FSPROGS_VERSION/e2fsprogs-$E2FSPROGS_VERSION.tar.gz"
echo "Building e2fsprogs for $ARCH..."
(cd "$WORK/e2fsprogs-$E2FSPROGS_VERSION" &&
    ./configure --host="$HOST" --prefix="$PREFIX" \
        --disable-nls --disable-imager --disable-resizer --disable-defrag \
        --disable-uuidd --disable-fuse2fs --disable-e2initrd-helper &&
    for lib in lib/et lib/ext2fs lib/e2p lib/uuid lib/blkid; do
        make -C "$lib" && make -C "$lib" install || exit 1
    done)

fetch "https://github.com/libsdl-org/SDL/releases/download/release-$SDL2_VERSION/SDL2-$SDL2_VERSION.tar.gz"
echo "Building SDL2 for $ARCH..."
(unset CC CFLAGS &&
    cmake -S "$WORK/SDL2-$SDL2_VERSION" -B "$WORK/sdl2-build" \
        -DCMAKE_BUILD_TYPE=Release -DCMAKE_INSTALL_PREFIX="$PREFIX" \
        -DCMAKE_OSX_ARCHITECTURES="$ARCH" \
        -DCMAKE_OSX_DEPLOYMENT_TARGET="$MACOSX_DEPLOYMENT_TARGET" \
        -DSDL_SHARED=OFF -DSDL_STATIC=ON -DSDL_TEST=OFF &&
    cmake --build "$WORK/sdl2-build" --parallel "$JOBS" &&
    cmake --install "$WORK/sdl2-build")

# sdl2-config --static-libs lists libSDL2.a's framework/system deps
# (Cocoa, IOKit, Metal, ...); keep everything but SDL2 itself (as -lSDL2
# or as the .a's path, depending on how SDL2 was built), added up front.
SDL2_LIBS="$PREFIX/lib/libSDL2.a"
for flag in $("$PREFIX/bin/sdl2-config" --static-libs); do
    case "$flag" in
        -L*|-lSDL2|-lSDL2main|*/libSDL2.a) ;;
        -Wl,-framework,*) SDL2_LIBS="$SDL2_LIBS;-framework ${flag#-Wl,-framework,}" ;;
        -Wl,-weak_framework,*) SDL2_LIBS="$SDL2_LIBS;-weak_framework ${flag#-Wl,-weak_framework,}" ;;
        *) SDL2_LIBS="$SDL2_LIBS;$flag" ;;
    esac
done

cat > "$PREFIX/deps.cmake" <<EOF
# Generated by scripts/build_deps_macos.sh -- use with: cmake -C $PREFIX/deps.cmake
set(CMAKE_OSX_ARCHITECTURES "$ARCH" CACHE STRING "")
set(CMAKE_OSX_DEPLOYMENT_TARGET "$MACOSX_DEPLOYMENT_TARGET" CACHE STRING "")
set(CMAKE_DISABLE_FIND_PACKAGE_SDL2 ON CACHE BOOL "")
set(CURL_INCLUDE_DIR "$SDK/usr/include" CACHE PATH "")
set(CURL_LIBRARY "$SDK/usr/lib/libcurl.tbd" CACHE FILEPATH "")
set(LZMA_INCLUDE_DIR "$PREFIX/include" CACHE PATH "")
set(LZMA_LIBRARY "$PREFIX/lib/liblzma.a" CACHE FILEPATH "")
set(E2FSPROGS_INCLUDE_DIR "$PREFIX/include" CACHE PATH "")
set(E2FSPROGS_ext2fs_LIBRARY "$PREFIX/lib/libext2fs.a" CACHE FILEPATH "")
set(E2FSPROGS_e2p_LIBRARY "$PREFIX/lib/libe2p.a" CACHE FILEPATH "")
set(E2FSPROGS_com_err_LIBRARY "$PREFIX/lib/libcom_err.a" CACHE FILEPATH "")
set(E2FSPROGS_blkid_LIBRARY "$PREFIX/lib/libblkid.a" CACHE FILEPATH "")
set(E2FSPROGS_uuid_LIBRARY "$PREFIX/lib/libuuid.a" CACHE FILEPATH "")
set(SDL2_INCLUDE_DIRS "$PREFIX/include/SDL2" CACHE PATH "")
set(SDL2_LIBRARIES "$SDL2_LIBS" CACHE STRING "")
EOF
echo "Done: $PREFIX/deps.cmake"
